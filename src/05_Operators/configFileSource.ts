import type { IdNameMapGeneric } from "../01_SpreadsheetSchema/configReaders/idNameMapTypes";
import {
  type ColumnConfigsGeneric,
  makeImportLine,
} from "../01_SpreadsheetSchema/configReaders/makeConfigs";
import type { WideAlterations } from "../01_SpreadsheetSchema/configReaders/SyncPlanner/wideAlterations";

function oneLineJsonObject(record: object): string {
  const fields = Object.entries(record).map(
    ([key, value]) => `${JSON.stringify(key)}: ${JSON.stringify(value)}`,
  );
  return `{ ${fields.join(", ")} }`;
}

// Each group opens a block and each record in it is one line, so a grep for a key finds one record.
export function oneLinePerLeafFileSource(
  configs: Record<string, Record<string, object>>,
): string {
  const groups = Object.entries(configs);
  if (groups.length === 0) {
    return "{}";
  }
  const blocks = groups.map(([groupKey, records]) => {
    const lines = Object.entries(records).map(
      ([recordKey, record]) =>
        `    ${JSON.stringify(recordKey)}: ${oneLineJsonObject(record)}`,
    );
    return `  ${JSON.stringify(groupKey)}: {\n${lines.join(",\n")}\n  }`;
  });
  return `{\n${blocks.join(",\n")}\n}`;
}

function isPlainObject(value: unknown): value is object {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

// An object holding a plain object opens a block; any other value is one line.
function alterationsValueSource(value: unknown, depth: number): string {
  if (!isPlainObject(value)) {
    return JSON.stringify(value);
  }
  const entries = Object.entries(value).filter(
    ([, field]) => field !== undefined,
  );
  if (entries.length === 0) {
    return "{}";
  }
  if (!entries.some(([, field]) => isPlainObject(field))) {
    return oneLineJsonObject(Object.fromEntries(entries));
  }
  const indent = "  ".repeat(depth + 1);
  const lines = entries.map(
    ([key, field]) =>
      `${indent}${JSON.stringify(key)}: ${alterationsValueSource(field, depth + 1)}`,
  );
  return `{\n${lines.join(",\n")}\n${"  ".repeat(depth)}}`;
}

export function alterationsFileSource(alterations: WideAlterations): string {
  return [
    "// sync rewrites this file: each alteration that lands is removed, and comments here won't survive a run.",
    makeImportLine(["makePendingAlterations"]),
    ``,
    `export const pendingAlterations = makePendingAlterations(${alterationsValueSource(alterations, 0)});`,
    ``,
  ].join("\n");
}

export const idNameMapOpening = "export interface IdNameMap ";

export function columnIdsByName(
  tableColumnConfigs: ColumnConfigsGeneric[string],
): Record<string, string> {
  return Object.entries(tableColumnConfigs).reduce<Record<string, string>>(
    (byName, [columnName, columnConfig]) => {
      byName[columnName] = columnConfig.columnId;
      return byName;
    },
    {},
  );
}

export function columnNamesByColumnId(
  tableColumnConfigs: ColumnConfigsGeneric[string],
): Map<string, string> {
  return Object.entries(columnIdsByName(tableColumnConfigs)).reduce(
    (namesById, [columnName, columnId]) => namesById.set(columnId, columnName),
    new Map<string, string>(),
  );
}

// The body is JSON, which is also a TypeScript type literal, so the file holds a type and no runtime value.
export function idNameMapFileSource(idNameMap: IdNameMapGeneric): string {
  return [
    "// Generated by gen:configs; never edit by hand. Each Table by ID, each tab by GID.",
    `${idNameMapOpening}${tablesAndTabsFileSource(idNameMap, oneLinePerEntryFileSource)}`,
    ``,
  ].join("\n");
}

interface TablesAndTabs<GG extends object> {
  tables: GG;
  tabs: GG;
}

export function tablesAndTabsFileSource<GG extends object>(
  { tables, tabs }: TablesAndTabs<GG>,
  groupFileSource: (group: GG) => string,
): string {
  return [
    `{`,
    `  "tables": ${indentFollowingLines(groupFileSource(tables))},`,
    `  "tabs": ${indentFollowingLines(groupFileSource(tabs))}`,
    `}`,
  ].join("\n");
}

function indentFollowingLines(text: string): string {
  return text.split("\n").join("\n  ");
}

export function oneLinePerEntryFileSource(
  configs: Record<string, object>,
): string {
  const entries = Object.entries(configs);
  if (entries.length === 0) {
    return "{}";
  }
  const lines = entries.map(
    ([key, config]) => `  ${JSON.stringify(key)}: ${oneLineJsonObject(config)}`,
  );
  return `{\n${lines.join(",\n")}\n}`;
}
